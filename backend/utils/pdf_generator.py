# --- Color Palette ---
PRIMARY = HexColor('#2563EB')
SECONDARY = HexColor('#00C2CC')
TEXT_DARK = HexColor('#0A0A0A')
TEXT_BODY = HexColor('#333333')
TEXT_MUTED = HexColor('#666666')
BG_LIGHT = HexColor('#F8FAFC')
BORDER_LIGHT = HexColor('#E2E8F0')


def _get_styles():
    """Build custom paragraph styles."""
    styles = getSampleStyleSheet()

    styles.add(ParagraphStyle(
        name='DocTitle',
        fontName='Helvetica-Bold',
        fontSize=16,
        leading=20,
        alignment=TA_CENTER,
        textColor=TEXT_DARK,
        spaceAfter=6,
    ))
    styles.add(ParagraphStyle(
        name='SectionHeader',
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=TEXT_DARK,
        spaceBefore=14,
        spaceAfter=6,
    ))
    styles.add(ParagraphStyle(
        name='BodyText10',
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=TEXT_BODY,
        spaceAfter=4,
    ))
    styles.add(ParagraphStyle(
        name='BodyBold',
        fontName='Helvetica-Bold',
        fontSize=10,
        leading=14,
        textColor=TEXT_DARK,
        spaceAfter=4,
    ))
    styles.add(ParagraphStyle(
        name='FooterStyle',
        fontName='Helvetica',
        fontSize=8,
        leading=10,
        alignment=TA_CENTER,
        textColor=TEXT_MUTED,
    ))
    styles.add(ParagraphStyle(
        name='FinancialRight',
        fontName='Helvetica-Bold',
        fontSize=11,
        leading=14,
        alignment=TA_RIGHT,
        textColor=TEXT_DARK,
    ))
    styles.add(ParagraphStyle(
        name='InvoiceHeader',
        fontName='Helvetica-Bold',
        fontSize=22,
        leading=28,
        alignment=TA_CENTER,
        textColor=white,
        spaceAfter=8,
    ))
    return styles


def _header_footer(canvas_obj, doc, title="VoiceContract", subtitle=""):
    """Draw header bar and footer on every page."""
    canvas_obj.saveState()
    width, height = A4

    # Header bar
    canvas_obj.setFillColor(PRIMARY)
    canvas_obj.rect(0, height - 50, width, 50, fill=1, stroke=0)
    canvas_obj.setFillColor(white)
    canvas_obj.setFont("Helvetica-Bold", 16)
    canvas_obj.drawString(30, height - 35, "VoiceContract")
    if subtitle:
        canvas_obj.setFont("Helvetica", 9)
        canvas_obj.drawRightString(width - 30, height - 35, subtitle)

    # Footer
    canvas_obj.setFillColor(TEXT_MUTED)
    canvas_obj.setFont("Helvetica", 7)
    canvas_obj.drawCentredString(width / 2, 20, f"Page {doc.page}  •  Generated by VoiceContract AI  •  {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}")
    canvas_obj.restoreState()


def _draw_watermark(canvas_obj, stamp_text: str):
    """Draw a diagonal crypto stamp watermark."""
    canvas_obj.saveState()
    width, height = A4
    canvas_obj.setFillColor(HexColor('#00C2CC'))
    canvas_obj.setFillAlpha(0.06)
    canvas_obj.setFont("Helvetica-Bold", 36)
    canvas_obj.translate(width / 2, height / 2)
    canvas_obj.rotate(45)
    text = f"SECURED: {stamp_text[:40]}"
    canvas_obj.drawCentredString(0, 0, text)
    canvas_obj.restoreState()


def _draw_signature_strokes(canvas_obj, strokes, offset_x, offset_y, box_width=180, box_height=60):
    """Draw biometric signature strokes onto the canvas."""
    canvas_obj.saveState()
    canvas_obj.setStrokeColor(TEXT_DARK)
    canvas_obj.setLineWidth(1.2)

    # Draw signature box border
    canvas_obj.setStrokeColor(SECONDARY)
    canvas_obj.setLineWidth(0.5)
    canvas_obj.rect(offset_x, offset_y - box_height, box_width, box_height, fill=0, stroke=1)

    canvas_obj.setStrokeColor(TEXT_DARK)
    canvas_obj.setLineWidth(1.2)

    for stroke in strokes:
        points = stroke.get("points", [])
        if not points or len(points) < 2:
            continue
        path = canvas_obj.beginPath()
        x0 = offset_x + points[0].get("x", 0) * box_width
        y0 = offset_y - points[0].get("y", 0) * box_height
        path.moveTo(x0, y0)
        for pt in points[1:]:
            x = offset_x + pt.get("x", 0) * box_width
            y = offset_y - pt.get("y", 0) * box_height
            path.lineTo(x, y)
        canvas_obj.drawPath(path, fill=0, stroke=1)

    canvas_obj.restoreState()


def _parse_contract_paragraphs(contract_text: str, styles):
    """Parse contract text into styled ReportLab flowables."""
    flowables = []
    paragraphs = contract_text.replace("\r", "").split("\n")

    for para in paragraphs:
        para = para.strip()
        if not para:
            flowables.append(Spacer(1, 6))
            continue

        # Escape XML special chars for ReportLab Paragraph
        safe = para.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

        # Document Title (all caps, short)
        if para.isupper() and len(para) < 60 and not any(c.isdigit() for c in para):
            flowables.append(Paragraph(safe, styles['DocTitle']))
        # Section Headers (e.g., "1. SCOPE OF SERVICES")
        elif len(para) > 2 and para[0].isdigit() and '.' in para[:4] and para.upper() == para:
            flowables.append(Paragraph(safe, styles['SectionHeader']))
        # Financial totals
        elif any(kw in para for kw in ["Subtotal:", "IGST", "CGST", "SGST", "Grand Total:"]):
            flowables.append(Paragraph(safe, styles['FinancialRight']))
        # Key-Value Pairs
        elif ":" in para and len(para.split(":")[0]) < 25:
            parts = para.split(":", 1)
            formatted = f"<b>{parts[0].replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')}:</b> {parts[1].strip().replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')}"
            flowables.append(Paragraph(formatted, styles['BodyText10']))
        # Standard body text
        else:
            flowables.append(Paragraph(safe, styles['BodyText10']))

    return flowables


