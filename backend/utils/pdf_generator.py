def generate_locked_pdf(contract_text: str, signature_strokes: list, metadata: dict) -> bytes:
    """
    Generate a locked PDF with single signature (backward-compatible).
    Used by signature.py for provider-signed contracts.
    """
    buffer = io.BytesIO()
    styles = _get_styles()
    crypto_stamp = metadata.get("crypto_stamp", "UNVERIFIED")
    session_id = metadata.get("session_id", "Unknown")

    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        topMargin=65, bottomMargin=40,
        leftMargin=30, rightMargin=30,
        title=f"Secured MSA - {session_id}",
        author="VoiceContract Nexus",
        subject=json.dumps(metadata),
    )

    flowables = _parse_contract_paragraphs(contract_text, styles)

    # Signature section
    flowables.append(Spacer(1, 30))
    flowables.append(HRFlowable(width="100%", thickness=1, color=BORDER_LIGHT, spaceAfter=12))
    flowables.append(Paragraph("EXECUTED &amp; DIGITALLY SIGNED:", styles['SectionHeader']))
    flowables.append(Spacer(1, 8))

    # Placeholder for signature — actual strokes drawn in onPage
    sig_label = Paragraph(
        f"<font size='8' color='#666666'>Biometric Signature — Crypto Stamp: {crypto_stamp[:32]}...</font>",
        styles['BodyText10']
    )
    flowables.append(sig_label)
    flowables.append(Spacer(1, 70))  # Reserve space for signature drawing

    # Metadata footer
    flowables.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_LIGHT, spaceAfter=6))
    ts = metadata.get("timestamp", datetime.utcnow().isoformat())
    flowables.append(Paragraph(
        f"<font size='7' color='#999999'>Session: {session_id} | Timestamp: {ts} | Integrity: SHA-256</font>",
        styles['FooterStyle']
    ))

    # Build with custom header/footer/watermark
    def on_page(c, d):
        _header_footer(c, d, subtitle="Master Service Agreement")
        _draw_watermark(c, crypto_stamp)
        # Draw signature strokes at a fixed position near the bottom
        if signature_strokes:
            page_w, page_h = A4
            _draw_signature_strokes(c, signature_strokes, offset_x=30, offset_y=160, box_width=180, box_height=60)

    doc.build(flowables, onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()


def generate_msa_pdf(
    msa_text: str,
    provider_sig: list,
    client_sig: list,
    metadata: dict,
    provider_info: dict | None = None,
    client_info: dict | None = None,
) -> bytes:
    """
    Generate an MSA PDF with dual signature blocks (Provider + Client).
    """
    buffer = io.BytesIO()
    styles = _get_styles()
    crypto_stamp = metadata.get("crypto_stamp", "UNVERIFIED")
    session_id = metadata.get("session_id", "Unknown")
    prov = provider_info or {}
    cli = client_info or {}

    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        topMargin=65, bottomMargin=40,
        leftMargin=30, rightMargin=30,
        title=f"MSA - {session_id}",
        author="VoiceContract Nexus",
        subject=json.dumps(metadata),
    )

    flowables = _parse_contract_paragraphs(msa_text, styles)

    # Party information table
    flowables.append(Spacer(1, 20))
    flowables.append(HRFlowable(width="100%", thickness=1, color=BORDER_LIGHT, spaceAfter=12))

    party_data = [
        [
            Paragraph("<b>SERVICE PROVIDER</b>", styles['BodyBold']),
            Paragraph("<b>CLIENT</b>", styles['BodyBold']),
        ],
        [
            Paragraph(f"{prov.get('company_name', 'Provider')}<br/>{prov.get('address', '')}<br/>GST: {prov.get('gst_number', 'N/A')}", styles['BodyText10']),
            Paragraph(f"{cli.get('client_name', 'Client')}<br/>{cli.get('client_company', '')}<br/>{cli.get('client_address', '')}<br/>{cli.get('client_email', '')}", styles['BodyText10']),
        ]
    ]
    party_table = Table(party_data, colWidths=[250, 250])
    party_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LINEBELOW', (0, 0), (-1, 0), 1, BORDER_LIGHT),
    ]))
    flowables.append(party_table)

    # Dual signature section
    flowables.append(Spacer(1, 24))
    flowables.append(Paragraph("EXECUTED &amp; DIGITALLY SIGNED BY BOTH PARTIES:", styles['SectionHeader']))
    flowables.append(Spacer(1, 8))

    sig_data = [
        [
            Paragraph("<b>Provider Signature</b>", styles['BodyBold']),
            Paragraph("<b>Client Signature</b>", styles['BodyBold']),
        ],
        [
            Paragraph("<font size='7' color='#999'>Biometric signature below</font>", styles['BodyText10']),
            Paragraph("<font size='7' color='#999'>Biometric signature below</font>", styles['BodyText10']),
        ]
    ]
    sig_table = Table(sig_data, colWidths=[250, 250])
    sig_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    flowables.append(sig_table)
    flowables.append(Spacer(1, 80))  # Reserve space for signature drawings

    # Metadata
    flowables.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_LIGHT, spaceAfter=6))
    flowables.append(Paragraph(
        f"<font size='7' color='#999999'>Crypto Stamp: {crypto_stamp} | Session: {session_id}</font>",
        styles['FooterStyle']
    ))

    def on_page(c, d):
        _header_footer(c, d, subtitle="Master Service Agreement")
        _draw_watermark(c, crypto_stamp)
        # Draw dual signatures
        if provider_sig:
            _draw_signature_strokes(c, provider_sig, offset_x=30, offset_y=170, box_width=180, box_height=60)
        if client_sig:
            _draw_signature_strokes(c, client_sig, offset_x=310, offset_y=170, box_width=180, box_height=60)

    doc.build(flowables, onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()


def generate_invoice_pdf(
    invoice_data: dict,
    metadata: dict,
    provider_info: dict | None = None,
    client_info: dict | None = None,
) -> bytes:
    """
    Generate a professional GST Tax Invoice PDF.
    
    invoice_data keys:
        invoice_number, date, due_date, items (list of dicts),
        subtotal, tax_rate, tax_amount, grand_total,
        bank_details (dict with bank_name, account_number, ifsc, branch)
    """
    buffer = io.BytesIO()
    styles = _get_styles()
    prov = provider_info or {}
    cli = client_info or {}
    session_id = metadata.get("session_id", "Unknown")

    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        topMargin=65, bottomMargin=40,
        leftMargin=30, rightMargin=30,
        title=f"Tax Invoice - {invoice_data.get('invoice_number', 'N/A')}",
        author="VoiceContract Nexus",
    )

    flowables = []

    # Invoice header
    flowables.append(Paragraph("TAX INVOICE", styles['DocTitle']))
    flowables.append(Spacer(1, 4))
    flowables.append(HRFlowable(width="100%", thickness=2, color=PRIMARY, spaceAfter=16))

    # Invoice meta info
    inv_meta = [
        [
            Paragraph(f"<b>Invoice #:</b> {invoice_data.get('invoice_number', 'N/A')}", styles['BodyText10']),
            Paragraph(f"<b>Date:</b> {invoice_data.get('date', datetime.utcnow().strftime('%B %d, %Y'))}", styles['BodyText10']),
        ],
        [
            Paragraph(f"<b>Due Date:</b> {invoice_data.get('due_date', 'On Receipt')}", styles['BodyText10']),
            Paragraph("", styles['BodyText10']),
        ],
    ]
    meta_table = Table(inv_meta, colWidths=[270, 250])
    meta_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    flowables.append(meta_table)
    flowables.append(Spacer(1, 16))

    # From / To blocks
    from_to = [
        [
            Paragraph("<b>FROM (Service Provider)</b>", styles['BodyBold']),
            Paragraph("<b>TO (Client)</b>", styles['BodyBold']),
        ],
        [
            Paragraph(
                f"{prov.get('company_name', 'Provider')}<br/>"
                f"{prov.get('address', '')}<br/>"
                f"GST: {prov.get('gst_number', 'N/A')}",
                styles['BodyText10']
            ),
            Paragraph(
                f"{cli.get('client_name', 'Client')}<br/>"
                f"{cli.get('client_company', '')}<br/>"
                f"{cli.get('client_address', '')}<br/>"
                f"{cli.get('client_email', '')}",
                styles['BodyText10']
            ),
        ]
    ]
    from_to_table = Table(from_to, colWidths=[270, 250])
    from_to_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LINEBELOW', (0, 0), (-1, 0), 1, PRIMARY),
        ('BACKGROUND', (0, 0), (-1, 0), HexColor('#F0F4FF')),
    ]))
    flowables.append(from_to_table)
    flowables.append(Spacer(1, 20))

    # Items table
    items = invoice_data.get("items", [])
    header_row = [
        Paragraph("<b>Description</b>", styles['BodyBold']),
        Paragraph("<b>HSN/SAC</b>", styles['BodyBold']),
        Paragraph("<b>Qty</b>", styles['BodyBold']),
        Paragraph("<b>Rate (₹)</b>", styles['BodyBold']),
        Paragraph("<b>Amount (₹)</b>", styles['BodyBold']),
    ]
    table_data = [header_row]

    for item in items:
        row = [
            Paragraph(str(item.get("description", "Professional Services")), styles['BodyText10']),
            Paragraph(str(item.get("hsn_sac", "99831")), styles['BodyText10']),
            Paragraph(str(item.get("qty", 1)), styles['BodyText10']),
            Paragraph(f"₹{item.get('rate', item.get('amount', 0)):,.2f}", styles['BodyText10']),
            Paragraph(f"₹{item.get('amount', 0):,.2f}", styles['BodyText10']),
        ]
        table_data.append(row)

    items_table = Table(table_data, colWidths=[180, 60, 40, 90, 100])
    items_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), PRIMARY),
        ('TEXTCOLOR', (0, 0), (-1, 0), white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 10),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
        ('TOPPADDING', (0, 0), (-1, 0), 8),
        ('ALIGN', (1, 0), (-1, -1), 'CENTER'),
        ('ALIGN', (-1, 0), (-1, -1), 'RIGHT'),
        ('ALIGN', (-2, 0), (-2, -1), 'RIGHT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER_LIGHT),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [white, BG_LIGHT]),
        ('TOPPADDING', (0, 1), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 6),
    ]))
    flowables.append(items_table)
    flowables.append(Spacer(1, 16))

    # Tax calculations
    subtotal = invoice_data.get("subtotal", 0)
    tax_rate = invoice_data.get("tax_rate", 18)
    tax_amount = invoice_data.get("tax_amount", round(subtotal * 0.18, 2))
    grand_total = invoice_data.get("grand_total", round(subtotal + tax_amount, 2))

    # Determine tax type (inter-state vs intra-state)
    is_interstate = invoice_data.get("interstate", True)

    tax_rows = [
        ["", "", "", Paragraph("<b>Subtotal</b>", styles['BodyBold']), Paragraph(f"<b>₹{subtotal:,.2f}</b>", styles['FinancialRight'])],
    ]
    if is_interstate:
        tax_rows.append(
            ["", "", "", Paragraph(f"IGST@{tax_rate}%", styles['BodyText10']), Paragraph(f"₹{tax_amount:,.2f}", styles['FinancialRight'])]
        )
    else:
        half_tax = round(tax_amount / 2, 2)
        half_rate = round(tax_rate / 2, 1)
        tax_rows.append(
            ["", "", "", Paragraph(f"CGST@{half_rate}%", styles['BodyText10']), Paragraph(f"₹{half_tax:,.2f}", styles['FinancialRight'])]
        )
        tax_rows.append(
            ["", "", "", Paragraph(f"SGST@{half_rate}%", styles['BodyText10']), Paragraph(f"₹{half_tax:,.2f}", styles['FinancialRight'])]
        )
    tax_rows.append(
        ["", "", "", Paragraph("<b>Grand Total</b>", styles['BodyBold']), Paragraph(f"<b>₹{grand_total:,.2f}</b>", styles['FinancialRight'])]
    )

    tax_table = Table(tax_rows, colWidths=[180, 60, 40, 90, 100])
    tax_table.setStyle(TableStyle([
        ('ALIGN', (-1, 0), (-1, -1), 'RIGHT'),
        ('ALIGN', (-2, 0), (-2, -1), 'RIGHT'),
        ('LINEABOVE', (-2, -1), (-1, -1), 1.5, PRIMARY),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    flowables.append(tax_table)
    flowables.append(Spacer(1, 24))

    # Bank details
    bank = invoice_data.get("bank_details", {})
    if bank:
        flowables.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_LIGHT, spaceAfter=10))
        flowables.append(Paragraph("<b>Bank Details for Payment</b>", styles['SectionHeader']))
        bank_info = (
            f"Bank: {bank.get('bank_name', 'N/A')}<br/>"
            f"Account Number: {bank.get('account_number', 'N/A')}<br/>"
            f"IFSC Code: {bank.get('ifsc', 'N/A')}<br/>"
            f"Branch: {bank.get('branch', 'N/A')}"
        )
        flowables.append(Paragraph(bank_info, styles['BodyText10']))

    # Footer
    flowables.append(Spacer(1, 30))
    flowables.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_LIGHT, spaceAfter=8))
    flowables.append(Paragraph(
        "<font size='8' color='#999999'>Generated by VoiceContract AI  •  Powered by Antarik Technologies</font>",
        styles['FooterStyle']
    ))

    def on_page(c, d):
        _header_footer(c, d, subtitle="Tax Invoice")

    doc.build(flowables, onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()
